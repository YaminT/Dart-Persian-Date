// Writes lib/src/nowruz_data.dart: the Earth's heliocentric longitude and
// radius from VSOP87D, and observed Delta T.
//
// Run from the repository root with the two source files:
//
//   dart run tool/nowruz/generate.dart VSOP87D.ear deltat.data
//
// VSOP87D.ear: VSOP87 (Bretagnon and Francou, 1988), version D, Earth,
// https://cdsarc.cds.unistra.fr/ftp/VI/81/VSOP87D.ear
//
// deltat.data: monthly TT - UT1 from the U.S. Naval Observatory,
// https://maia.usno.navy.mil/ser7/deltat.data
import 'dart:io';

const _output = 'lib/src/nowruz_data.dart';

/// Terms below this amplitude (radians for L, AU for R) are dropped. With
/// it the equinoxes of 1981 to 2026 stay within 3 seconds of JPL DE440.
const _threshold = 5e-8;

void main(List<String> args) {
  if (args.length != 2) {
    stderr.writeln('Usage: dart run tool/nowruz/generate.dart '
        'VSOP87D.ear deltat.data');
    exit(64);
  }
  final series = _readVsop(args[0]);
  final deltaT = _readDeltaT(args[1]);
  final firstYear = deltaT.keys.reduce((a, b) => a < b ? a : b);
  final lastYear = deltaT.keys.reduce((a, b) => a > b ? a : b);

  String table(int variable) {
    final powers = <String>[];
    for (var power = 0; series.containsKey((variable, power)); power++) {
      final terms = series[(variable, power)]!
          .where((t) => double.parse(t.$1).abs() >= _threshold)
          .map((t) => '    (${t.$1}, ${t.$2}, ${t.$3}),')
          .join('\n');
      powers.add('  [\n$terms\n  ],');
    }
    return '[\n${powers.join('\n')}\n]';
  }

  final values = [
    for (var year = firstYear; year <= lastYear; year++) '  ${deltaT[year]},',
  ];
  File(_output).writeAsStringSync('''
// Generated by tool/nowruz/generate.dart from VSOP87D.ear (VSOP87, Bretagnon
// and Francou, 1988) and deltat.data (U.S. Naval Observatory). Do not edit by
// hand.

/// Series for the Earth's heliocentric longitude (radians) in VSOP87D,
/// referred to the mean ecliptic and equinox of the date, with the terms of
/// at least $_threshold. Element `i` is multiplied by the `i`th power of
/// Julian millennia from J2000; each term is (amplitude, phase, frequency).
const earthLongitude = <List<(double, double, double)>>${table(1)};

/// Series for the Earth's distance from the Sun (AU), like
/// [earthLongitude].
const earthRadius = <List<(double, double, double)>>${table(3)};

/// First year of [deltaT].
const deltaTFirstYear = $firstYear;

/// Observed TT - UT1 on 1 January of each year from [deltaTFirstYear], in
/// seconds.
const deltaT = <double>[
${values.join('\n')}
];
''');
  final format =
      Process.runSync(Platform.resolvedExecutable, ['format', _output]);
  if (format.exitCode != 0) throw StateError('dart format: ${format.stderr}');
  stdout.writeln('Wrote $_output, Delta T $firstYear to $lastYear');
}

/// Terms of each (variable, power) series as written in the file.
Map<(int, int), List<(String, String, String)>> _readVsop(String path) {
  final series = <(int, int), List<(String, String, String)>>{};
  List<(String, String, String)>? current;
  for (final line in File(path).readAsLinesSync()) {
    if (line.contains('VSOP87')) {
      final variable =
          int.parse(RegExp(r'VARIABLE (\d)').firstMatch(line)![1]!);
      final power = int.parse(RegExp(r'\*T\*\*(\d)').firstMatch(line)![1]!);
      current = series[(variable, power)] = [];
      continue;
    }
    final fields = line.trim().split(RegExp(r'\s+'));
    if (fields.length < 3) continue;
    final n = fields.length;
    current!.add((fields[n - 3], fields[n - 2], fields[n - 1]));
  }
  return series;
}

