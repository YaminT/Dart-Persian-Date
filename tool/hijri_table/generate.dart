// Writes lib/src/hijri_table.dart, and the same table for the npm package in
// packages/iranian_calendar_js/src/table.ts, from the official month starts
// in test/data/qamari_consolidated.txt and test/data/hijri_supplement.txt.
//
// Run from the repository root:
//
//   dart run tool/hijri_table/generate.dart
//
// To add a newly published calendar, append its months to
// hijri_supplement.txt and run this again; the predicted table then starts
// at the new officialLastMonth.
import 'dart:io';

import 'package:jalali_date/src/jalali_calc.dart';
import 'package:jalali_date/src/hijri.dart' show calculatedMonthStart;

const _sources = [
  'test/data/qamari_consolidated.txt',
  'test/data/hijri_supplement.txt',
];
const _output = 'lib/src/hijri_table.dart';
const _outputTs = 'packages/iranian_calendar_js/src/table.ts';

final _line = RegExp(r'^\*?(\d+)/(\d+) (\d+)-(\d+)-(\d+)\s*(#.*)?$');

void main() {
  final starts = <int, int>{};
  for (final path in _sources) {
    for (final (i, line) in File(path).readAsLinesSync().indexed) {
      if (line.trim().isEmpty || line.startsWith('#')) continue;
      final m = _line.firstMatch(line);
      if (m == null) throw FormatException('$path:${i + 1}: $line');
      final index = int.parse(m[1]!) * 12 + int.parse(m[2]!) - 1;
      if (starts.containsKey(index)) {
        throw FormatException('$path:${i + 1}: month listed twice');
      }
      starts[index] = g2d(int.parse(m[3]!), int.parse(m[4]!), int.parse(m[5]!));
    }
  }

  final first = starts.keys.reduce((a, b) => a < b ? a : b);
  final last = starts.keys.reduce((a, b) => a > b ? a : b);
  if (first % 12 != 0) throw StateError('The data must start at Muharram');
  final masks = <int>[];
  for (var index = first; index < last; index++) {
    final start = starts[index], next = starts[index + 1];
    if (start == null || next == null) {
      throw StateError(
          'Missing month ${_name(start == null ? index : index + 1)}');
    }
    final length = next - start;
    if (length != 29 && length != 30) {
      throw StateError('${_name(index)} has $length days');
    }
    if ((index - first) % 12 == 0) masks.add(0);
    if (length == 30) masks[masks.length - 1] |= 1 << (index - first) % 12;
  }

  final rows = [
    for (var i = 0; i < masks.length; i += 20)
      "'${masks.skip(i).take(20).map(_hex).join()}'",
  ];
  final predictedLast = 1551 * 12; // exclusive: Muharram 1551
  final predictedBits = <int>[];
  for (var index = last; index < predictedLast; index++) {
    final start = index == last ? starts[last]! : calculatedMonthStart(index);
    final next = calculatedMonthStart(index + 1);
    final length = next - start;
    if (length != 29 && length != 30) {
      throw StateError('${_name(index)} has predicted length $length');
    }
    predictedBits.add(length == 30 ? 1 : 0);
  }
  final predictedHex = <String>[];
  for (var i = 0; i < predictedBits.length; i += 4) {
    var nibble = 0;
    for (var bit = 0; bit < 4 && i + bit < predictedBits.length; bit++) {
      nibble |= predictedBits[i + bit] << bit;
    }
    predictedHex.add(nibble.toRadixString(16).toUpperCase());
  }
  final predictedRows = [
    for (var i = 0; i < predictedHex.length; i += 60)
      "'${predictedHex.skip(i).take(60).join()}'",
  ];
  File(_output).writeAsStringSync('''
// Generated by tool/hijri_table/generate.dart from
// test/data/qamari_consolidated.txt and test/data/hijri_supplement.txt.
// Do not edit by hand.

/// First month of [officialMonthLengths], as `year * 12 + month - 1`
/// (Muharram ${first ~/ 12}).
const officialFirstMonth = $first;

/// Last month whose first day the official record fixes, as
/// `year * 12 + month - 1` (${_name(last)}).
const officialLastMonth = $last;

/// Julian day number of the first day of [officialFirstMonth].
const officialFirstDay = ${starts[first]};

/// Lengths of the months from [officialFirstMonth] to the month before
/// [officialLastMonth], three hexadecimal digits per Hijri year: bit
/// `month - 1` of a year's mask is set when that month has 30 days.
const officialMonthLengths =
    ${rows.join('\n    ')};

/// Exclusive end (Muharram 1551); predicted lengths cover
/// [officialLastMonth, predictedLastMonth), through Dhu al-Hijjah 1550.
const predictedLastMonth = $predictedLast;

/// One bit per month from [officialLastMonth]: bit 0 is Shawwal 1448.
/// A set bit means 30 days; bits are packed low-to-high in each hex nibble.
const predictedMonthLengths =
    ${predictedRows.join('\n    ')};
''');
  final format =
      Process.runSync(Platform.resolvedExecutable, ['format', _output]);
  if (format.exitCode != 0) throw StateError('dart format: ${format.stderr}');
  File(_outputTs).writeAsStringSync('''
// Generated by tool/hijri_table/generate.dart from
// test/data/qamari_consolidated.txt and test/data/hijri_supplement.txt at the
// repository root. Do not edit by hand.

/** First month of the official record, as `year * 12 + month - 1` (Muharram ${first ~/ 12}). */
export const officialFirstMonth = $first;

/** Last month whose first day the official record fixes, as `year * 12 + month - 1` (${_name(last)}). */
export const officialLastMonth = $last;

/** Julian day number of the first day of `officialFirstMonth`. */
export const officialFirstDay = ${starts[first]};

/**
 * Lengths of the months from `officialFirstMonth` to the month before
 * `officialLastMonth`, three hexadecimal digits per Hijri year: bit
 * `month - 1` of a year's mask is set when that month has 30 days.
 */
export const officialMonthLengths =
  ${rows.join(' +\n  ')};

/** Exclusive end (Muharram 1551), covering predicted lengths through Dhu al-Hijjah 1550. */
export const predictedLastMonth = $predictedLast;

/** One bit per month from `officialLastMonth` (bit 0 is Shawwal 1448); set means 30 days, low-to-high per hex nibble. */
export const predictedMonthLengths =
  ${predictedRows.join(' +\n  ')};
''');
  stdout.writeln(
      'Wrote $_output and $_outputTs: ${_name(first)} to ${_name(last)}, '
      '${last - first + 1} month starts');
}

String _name(int index) => '${index ~/ 12}/${index % 12 + 1}';

String _hex(int mask) => mask.toRadixString(16).toUpperCase().padLeft(3, '0');
